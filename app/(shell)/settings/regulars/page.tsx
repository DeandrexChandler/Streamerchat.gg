"use client";

import { useEffect, useState } from "react";
import { Plus, Trash2 } from "lucide-react";
import { Button } from "@/components/ui/button";
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Badge } from "@/components/ui/badge";
import { localRosterStore, type SavedViewer } from "@/lib/config/roster-store";
import { useStoredSettings } from "@/lib/react/use-stored-settings";
import { makeRegular } from "@/lib/config/make-regular";
import { PERSONALITIES } from "@/lib/data/personalities";
import { describeVoice } from "@/lib/data/voices";
import { isConversational, rosterSizeFor } from "@/lib/engine/roster";
import type { Voice } from "@/lib/engine/types";

/**
 * The regulars, as the model is told about them — and editable.
 *
 * Everything here is generated by default, from measured ranges. What the
 * streamer knows and the ranges cannot is character: who these people are
 * to them. So the one free-text field outranks the rest in the prompt, and
 * anyone touched here is pinned — never rotated out, and never quietly
 * overwritten by a session writing its memory back.
 */

const ARCHETYPES = Object.values(PERSONALITIES);

/** The habit sliders, in the order they read as a person. */
const HABITS: ReadonlyArray<{ key: keyof Voice; label: string; max: number }> = [
  { key: "words", label: "Line length", max: 12 },
  { key: "caps", label: "Shouting", max: 0.45 },
  { key: "punctuation", label: "Punctuation", max: 0.45 },
  { key: "questions", label: "Questions", max: 0.45 },
  { key: "stretch", label: "Stretched wordsss", max: 0.45 },
];

export default function RegularsSettingsPage() {
  const { settings } = useStoredSettings();
  const [roster, setRoster] = useState<SavedViewer[] | null>(null);

  useEffect(() => {
    // Client-only storage cannot be read during render without desyncing
    // server and client markup, so the one extra mount render is deliberate
    // — the same trade `useStoredSettings` documents.
    // eslint-disable-next-line react-hooks/set-state-in-effect
    setRoster(localRosterStore.load());
  }, []);

  const loaded = roster !== null;
  const people = roster ?? [];

  /** Every change writes straight through: there is no Save button to forget. */
  const write = (next: SavedViewer[]) => {
    setRoster(next);
    localRosterStore.replace(next);
  };

  const update = (id: string, patch: Partial<SavedViewer>) => {
    write(
      people.map((viewer) =>
        viewer.id === id ? { ...viewer, ...patch, pinned: true } : viewer,
      ),
    );
  };

  const rate = settings.messagesPerSecond;
  const inRoom = rosterSizeFor(rate);
  const conversational = isConversational(rate);

  return (
    <div className="mx-auto max-w-3xl space-y-5 pb-10">
      <Card>
        <CardHeader>
          <CardTitle>Your regulars</CardTitle>
          <CardDescription>
            {conversational
              ? "At your current chat speed these people are written by name, in their own voice, and they remember your stream between sessions."
              : "At your current chat speed chat is a crowd, so names are not sent to the AI. These people still fill the room; drop to 0.5 or 0.2 messages a second to talk to them by name."}{" "}
            Anyone you edit is kept exactly as you leave them. Changes apply
            the next time you press Play.
          </CardDescription>
        </CardHeader>
        <CardContent className="space-y-4">
          {!loaded ? null : people.length === 0 ? (
            <p className="text-sm text-muted-foreground">
              Nobody yet. Run a session and the room fills in here, or add
              someone below.
            </p>
          ) : (
            <>
              {people.length > inRoom && (
                <p className="text-xs text-muted-foreground">
                  Your speed has room for {inRoom}. Edited people are kept
                  first, then whoever spoke most recently.
                </p>
              )}
              {people.map((viewer) => (
                <Regular
                  key={viewer.id}
                  viewer={viewer}
                  onChange={(patch) => update(viewer.id, patch)}
                  onDelete={() => write(people.filter((v) => v.id !== viewer.id))}
                />
              ))}
            </>
          )}

          {loaded && (
            <Button
              variant="outline"
              disabled={people.length >= 12}
              onClick={() => write([...people, makeRegular(people)])}
            >
              <Plus className="size-4" />
              Add a regular
            </Button>
          )}
        </CardContent>
      </Card>

      {people.length > 0 && (
        <Card>
          <CardHeader>
            <CardTitle>Start over</CardTitle>
            <CardDescription>
              Forgets everyone, including anyone you wrote. The next session
              builds a new room with new names.
            </CardDescription>
          </CardHeader>
          <CardContent>
            <Button
              variant="outline"
              onClick={() => {
                localRosterStore.clear();
                setRoster([]);
              }}
            >
              Forget my regulars
            </Button>
          </CardContent>
        </Card>
      )}
    </div>
  );
}

function Regular({
  viewer,
  onChange,
  onDelete,
}: {
  viewer: SavedViewer;
  onChange: (patch: Partial<SavedViewer>) => void;
  onDelete: () => void;
}) {
  const voice = viewer.voice;

  return (
    <div className="space-y-3 rounded-lg border p-3">
      <div className="flex items-center gap-2">
        <Input
          value={viewer.name}
          aria-label="Name"
          maxLength={25}
          onChange={(e) => onChange({ name: e.target.value })}
          className="h-8 max-w-[14rem] font-medium"
          style={{ color: viewer.color }}
        />
        <select
          value={viewer.personality}
          aria-label="Archetype"
          onChange={(e) => onChange({ personality: e.target.value })}
          className="h-8 rounded-md border bg-transparent px-2 text-xs"
        >
          {ARCHETYPES.map((archetype) => (
            <option key={archetype.id} value={archetype.id}>
              {archetype.label}
            </option>
          ))}
        </select>
        {viewer.pinned && (
          <Badge variant="secondary" className="shrink-0">
            Yours
          </Badge>
        )}
        <Button
          variant="ghost"
          size="sm"
          aria-label={`Delete ${viewer.name}`}
          className="ml-auto text-muted-foreground"
          onClick={onDelete}
        >
          <Trash2 className="size-4" />
        </Button>
      </div>

      <div>
        <Input
          value={viewer.note ?? ""}
          aria-label={`What ${viewer.name} is like`}
          maxLength={200}
          placeholder="Who are they? e.g. streams at 3am, always hungry, hates the roof build"
          onChange={(e) => onChange({ note: e.target.value || undefined })}
          className="h-8 text-xs"
        />
        <p className="mt-1 text-[11px] text-muted-foreground">
          Sent to the AI in your words, and it outranks everything below.
        </p>
      </div>

      {voice && (
        <div className="grid gap-1.5 sm:grid-cols-2">
          {HABITS.map(({ key, label, max }) => (
            <label key={key} className="flex items-center gap-2 text-[11px]">
              <span className="w-28 shrink-0 text-muted-foreground">{label}</span>
              <input
                type="range"
                min={key === "words" ? 1 : 0}
                max={max}
                step={key === "words" ? 1 : 0.05}
                value={voice[key] as number}
                aria-label={`${label} for ${viewer.name}`}
                onChange={(e) =>
                  onChange({ voice: { ...voice, [key]: Number(e.target.value) } })
                }
                className="h-1 flex-1 accent-purple-500"
              />
            </label>
          ))}
        </div>
      )}

      {voice && (
        <p className="text-[11px] text-muted-foreground">
          {describeVoice(voice)}
        </p>
      )}

      {(viewer.memory.topics.length > 0 || viewer.memory.lines.length > 0) && (
        <div className="space-y-0.5 border-t pt-2 text-[11px]">
          {viewer.memory.topics.length > 0 && (
            <p>
              <span className="text-muted-foreground">Been on about: </span>
              {viewer.memory.topics.join(", ")}
            </p>
          )}
          {viewer.memory.lines.length > 0 && (
            <p>
              <span className="text-muted-foreground">Last said: </span>
              {viewer.memory.lines.map((line) => `"${line}"`).join(", ")}
            </p>
          )}
          {viewer.memory.addressed.length > 0 && (
            <p>
              <span className="text-muted-foreground">You said to them: </span>
              {viewer.memory.addressed.map((line) => `"${line}"`).join(", ")}
            </p>
          )}
          <Button
            variant="ghost"
            size="sm"
            className="h-6 px-1 text-[11px] text-muted-foreground"
            onClick={() =>
              onChange({ memory: { topics: [], lines: [], addressed: [] } })
            }
          >
            Clear what they remember
          </Button>
        </div>
      )}
    </div>
  );
}
